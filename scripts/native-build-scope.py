#!/usr/bin/env python3
"""Select native jobs from actual build inputs; runtime-only changes use JS checks.

Unknown native changes rebuild every target. Workflow edits also rebuild every
lane unless all changes are confined to Node-specific steps or admission logic.
The full matrix can always be requested with workflow_dispatch.
"""
import json
from pathlib import Path
import subprocess
import sys

NODE = [
    {"kind": "node", "target": "darwin-arm64", "runner": "macos-15"},
    {"kind": "node", "target": "darwin-x64", "runner": "macos-15-intel"},
    {"kind": "node", "target": "linux-x64-gnu", "runner": "ubuntu-22.04"},
    {"kind": "node", "target": "linux-arm64-gnu", "runner": "ubuntu-24.04-arm"},
    {"kind": "node", "target": "linux-x64-musl", "runner": "ubuntu-22.04"},
]
BARE = [
    {"kind": "bare", "target": "darwin-arm64", "runner": "macos-15"},
    {"kind": "bare", "target": "darwin-x64", "runner": "macos-15-intel"},
    {"kind": "bare", "target": "linux-x64", "runner": "ubuntu-22.04"},
    {"kind": "bare", "target": "linux-arm64", "runner": "ubuntu-24.04-arm"},
]


def git(*args):
    return subprocess.check_output(["git", *args], text=True)


def bare_workflow_inputs(text):
    """Keep complete mobile jobs and all shared/Bare desktop steps verbatim."""
    jobs = text.split("  android:\n", 1)
    if len(jobs) != 2:
        return text  # Unknown workflow layout cannot be proven equivalent.
    desktop = jobs[0].split("  desktop:\n", 1)
    if len(desktop) != 2:
        return text
    text = desktop[1]
    # Matrix is generated by this script; shared execution settings stay pinned.
    start = text.find("    env:\n")
    if start == -1:
        return text
    shared = text[start:].split("    steps:\n", 1)
    if len(shared) != 2:
        return text
    steps = []
    for step in shared[1].split("      - ")[1:]:
        if "if: matrix.kind == 'node'" in step or "name: Build and test in an actual musl userland" in step:
            continue
        steps.append(step)
    retained = shared[0] + "\n".join(steps) + jobs[1]
    return retained.replace("needs.native-admission.outputs.enabled", "needs.native-admission.outputs.bare")


def select(changed, before, after):
    node = bare = False
    for name in changed:
        if name.endswith(".md"):
            continue
        if name.startswith("native/node/") or name in ("native/Cargo.toml", "native/Cargo.lock", "native/src/main.rs", "native/scripts/check-dev-signet.py", "native/scripts/node-host.mjs"):
            node = True
        elif name.startswith("native/bare/") or name in ("native/scripts/build-bare.sh", "native/scripts/build-bare-android.sh", "native/scripts/build-bare-ios.sh", "native/scripts/verify-bare-android.mjs"):
            bare = True
        elif name.startswith("native/") or name == "src/onchain-dev-services.json":
            node = bare = True
        elif name == "package.json":
            if json.loads(before(name))["version"] != json.loads(after(name))["version"]:
                node = bare = True
        elif name == ".github/workflows/build.yml":
            node = True
            if bare_workflow_inputs(before(name)) != bare_workflow_inputs(after(name)):
                bare = True
    return node, bare


def main():
    mode, base, head = sys.argv[1:]
    if mode in ("all", "node"):
        node, bare = True, mode == "all"
    elif mode == "changes":
        receipt = json.loads(git("show", f"{head}:qualification/rc4/platforms.json"))
        producers = receipt.get("producers", {"node": receipt.get("producerCommit"), "bare": receipt.get("producerCommit")})
        selected = {}
        for runtime in ("node", "bare"):
            producer = producers[runtime]
            git("merge-base", "--is-ancestor", producer, head)
            changed = git("diff", "--name-only", producer, head).splitlines()
            selected[runtime] = select(changed, lambda path: git("show", f"{producer}:{path}"), lambda path: git("show", f"{head}:{path}"))
        node, bare = selected["node"][0], selected["bare"][1]
    else:
        raise SystemExit("Expected all, node, or changes")
    print(json.dumps({"enabled": node or bare, "bare": bare, "matrix": {"include": (NODE if node else []) + (BARE if bare else [])}}))


if __name__ == "__main__":
    main()
